package com.wavora.app.expect.ui

import androidx.compose.ui.graphics.Color

/**
 * Пипетка «взять цвет с экрана».
 *
 * WHY не просто «прочитать пиксель под курсором»: старый вариант читал цвет сразу по нажатию
 * кнопки, поэтому попадал в сам диалог, а «отсчёт по таймеру» заставлял угадывать момент.
 * Здесь на десктопе открывается прозрачный полноэкранный оверлей с курсором-прицелом:
 * пользователь кликает по нужному месту, и цвет забирается уже после того, как оверлей скрыт.
 *
 * На Android и iOS захват экрана требует отдельного разрешения (MediaProjection / ReplayKit),
 * поэтому там [onPicked] вызывается сразу с `null` — кнопка пипетки просто не показывается.
 */
expect fun startScreenColorPicker(onPicked: (Color?) -> Unit)
